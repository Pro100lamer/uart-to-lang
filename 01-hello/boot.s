/* Первая программа: печатаем строку через UART.
   Никакой ОС, никакого загрузчика, никакой стандартной библиотеки.
   Есть процессор, есть память, есть регистр UART по адресу 0x10000000.
   Байт, записанный по этому адресу, уходит в терминал.

   Именно байт, а не символ: цикл ниже про символы ничего не знает.
   «Привет, мир!» — двенадцать символов, но двадцать один байт: девять
   кириллических букв весят в UTF-8 по два байта, а запятая, пробел и
   восклицательный знак — по одному. С переводом строки в UART уйдёт
   двадцать два байта. */

    .section .text
    .globl _start

_start:
    li      t0, 0x10000000      /* регистр данных UART 16550 */
    la      t1, message         /* адрес первого байта строки */

next_char:
    lbu     t2, 0(t1)           /* берём очередной байт */
    beqz    t2, done            /* ноль — строка кончилась */
    sb      t2, 0(t0)           /* кладём байт в UART */
    addi    t1, t1, 1           /* сдвигаемся на байт вперёд */
    j       next_char

done:
    /* Возвращаться некуда: под нами нет ни ОС, ни вызывающего кода.
       Поэтому просто останавливаем процессор и остаёмся здесь навсегда. */
    wfi
    j       done

    .section .rodata
message:
    .string "Привет, мир!\n"
