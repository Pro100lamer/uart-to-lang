/* Прямая проверка: снимает ли QEMU бит THRE после записи в THR?
   На железе после записи байта передатчик занят, и THRE сбрасывается
   до тех пор, пока байт не уйдёт по линии.

   Пишем символ, тут же читаем LSR и печатаем 1, если THRE всё ещё
   выставлен, или 0, если он снялся. Десять раз подряд.

   Ожидание для железа: X0X0X0...
   Что получится в эмуляторе — смотрим. */

    .section .text
    .globl _start

_start:
    li      t0, 0x10000000

    /* Медленная линия: делитель 2048. Если бы QEMU моделировал
       время передачи, при такой скорости THRE обязан был бы
       сниматься надолго. */
    li      t4, 0x80
    sb      t4, 3(t0)
    li      t4, 0x00
    sb      t4, 0(t0)
    li      t4, 0x08
    sb      t4, 1(t0)
    li      t4, 0x03
    sb      t4, 3(t0)

    li      t5, 10              /* сколько раз повторить */

loop:
    li      t2, 'X'
    sb      t2, 0(t0)           /* пишем байт в THR */

    lbu     t3, 5(t0)           /* сразу читаем LSR */
    andi    t3, t3, 0x20        /* THRE */
    beqz    t3, busy

    li      t2, '1'             /* THRE всё ещё выставлен */
    j       report

busy:
    li      t2, '0'             /* THRE снялся, передатчик занят */

report:
    sb      t2, 0(t0)

    addi    t5, t5, -1
    bnez    t5, loop

    li      t2, '\n'
    sb      t2, 0(t0)

done:
    li      t0, 0x100000
    li      t1, 0x5555
    sw      t1, 0(t0)
1:  wfi
    j       1b
