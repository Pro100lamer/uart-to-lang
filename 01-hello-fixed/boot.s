/* «Привет, мир!» через UART, версия, которая работала бы на железе.

   Отличие от первой статьи в двух вещах, и обе всплыли из комментария
   читателя.

   Первое: UART надо настроить. Скорость линии задаётся делителем,
   формат кадра задаётся отдельно. В эмуляторе оно и без этого работает,
   на плате нет.

   Второе, главное: перед записью каждого байта надо дождаться, пока
   передатчик освободится. Он отдаёт байт по линии небыстро, и если
   писать в занятый регистр, новый байт затирает предыдущий. Процессор
   успевает записать сотни байт за то время, пока по линии уезжает один.
*/

    .equ UART_BASE,  0x10000000

    /* Смещения регистров NS16550A от базы. */
    .equ UART_THR,   0          /* передатчик, он же делитель при DLAB=1 */
    .equ UART_DLM,   1          /* старший байт делителя при DLAB=1     */
    .equ UART_LCR,   3          /* формат кадра и бит DLAB              */
    .equ UART_LSR,   5          /* состояние линии                      */

    .equ LCR_DLAB,   0x80       /* открыть доступ к делителю скорости   */
    .equ LCR_8N1,    0x03       /* 8 бит данных, без чётности, 1 стоп   */
    .equ LSR_THRE,   0x20       /* передатчик свободен                  */

    .equ DIVISOR,    1          /* делитель скорости линии              */

    .section .text
    .globl _start

_start:
    li      t0, UART_BASE

    /* Настройка линии. Сначала открываем делитель битом DLAB,
       кладём его младший и старший байты, потом закрываем DLAB
       и заодно задаём формат кадра. */
    li      t4, LCR_DLAB
    sb      t4, UART_LCR(t0)
    li      t4, DIVISOR
    sb      t4, UART_THR(t0)
    li      t4, 0
    sb      t4, UART_DLM(t0)
    li      t4, LCR_8N1
    sb      t4, UART_LCR(t0)

    la      t1, message

next_char:
    lbu     t2, 0(t1)
    beqz    t2, done

    /* Ждём, пока передатчик освободится. Ровно этих трёх инструкций
       не хватало в первой статье. */
wait_thre:
    lbu     t3, UART_LSR(t0)
    andi    t3, t3, LSR_THRE
    beqz    t3, wait_thre

    sb      t2, UART_THR(t0)
    addi    t1, t1, 1
    j       next_char

done:
    wfi
    j       done

    .section .rodata
message:
    .string "Привет, мир!\n"
