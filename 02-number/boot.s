/* Складываем числа и выводим результат числом.

   Две вещи, которых не было в первой статье.

   Первая: вывод в UART теперь правильный. Перед каждым байтом ждём,
   пока передатчик освободится. Без этого на железе всё сыплется, и
   первая статья была в этом месте неправа.

   Вторая: чтобы напечатать число, его надо превратить в строку, а для
   этого нужно деление на десять. В базовом наборе RV32I команды деления
   нет вообще. Делим вычитанием.
*/

    .equ UART_BASE,  0x10000000
    .equ UART_THR,   0
    .equ UART_DLM,   1
    .equ UART_LCR,   3
    .equ UART_LSR,   5

    .equ LCR_DLAB,   0x80
    .equ LCR_8N1,    0x03
    .equ LSR_THRE,   0x20
    .equ DIVISOR,    1

    .section .text
    .globl _start

_start:
    li      s0, UART_BASE       /* s0 держит базу UART всю программу */

    /* Настройка линии: делитель скорости и формат кадра 8N1. */
    li      t0, LCR_DLAB
    sb      t0, UART_LCR(s0)
    li      t0, DIVISOR
    sb      t0, UART_THR(s0)
    li      t0, 0
    sb      t0, UART_DLM(s0)
    li      t0, LCR_8N1
    sb      t0, UART_LCR(s0)

    /* Собственно арифметика. Два числа, сложение, результат в a0.
       Вот и всё, что процессор умеет делать с числами на этом уровне. */
    li      a1, 2
    li      a2, 2
    add     a0, a1, a2

    la      a3, msg_first
    jal     t4, print_str
    jal     t5, print_dec
    la      a3, msg_nl
    jal     t4, print_str

    /* Число побольше, чтобы деление на десять заработало не на одну
       цифру, а по-настоящему. */
    li      a1, 20000
    li      a2, 2345
    add     a0, a1, a2

    la      a3, msg_second
    jal     t4, print_str
    jal     t5, print_dec
    la      a3, msg_nl
    jal     t4, print_str

done:
    wfi
    j       done


/* putc: печатает байт из a4.
   Возврат через t6. Регистр для возврата выбран руками, потому что
   стека у нас пока нет, а значит вложенные вызовы через ra негде
   сохранять. Стек будет в следующей статье. */
putc:
1:  lbu     t0, UART_LSR(s0)
    andi    t0, t0, LSR_THRE
    beqz    t0, 1b
    sb      a4, UART_THR(s0)
    jr      t6


/* print_str: печатает строку, адрес в a3. Возврат через t4. */
print_str:
1:  lbu     a4, 0(a3)
    beqz    a4, 2f
    jal     t6, putc
    addi    a3, a3, 1
    j       1b
2:  jr      t4


/* print_dec: печатает беззнаковое число из a0. Возврат через t5.

   Цифры получаются с конца: остаток от деления на десять это последняя
   цифра. Значит складываем их в буфер задом наперёд, а потом печатаем
   от последней записанной к началу.

   Деления в RV32I нет, поэтому div10 ниже делает его вычитанием. */
print_dec:
    la      a5, numbuf
    addi    a5, a5, 15          /* конец буфера, пишем справа налево */
    li      t0, 0
    sb      t0, 0(a5)           /* завершающий ноль */

    /* Ноль надо обработать отдельно: цикл ниже не сделал бы ни одного
       оборота и не вывел бы ни одной цифры. */
    bnez    a0, 1f
    addi    a5, a5, -1
    li      t0, '0'
    sb      t0, 0(a5)
    j       3f

1:  /* a0 = число, a5 = куда писать следующую цифру */
    beqz    a0, 3f
    jal     t3, div10           /* a0 -> частное, a1 -> остаток */
    addi    a1, a1, '0'         /* цифра в символ: 4 превращается в '4' */
    addi    a5, a5, -1
    sb      a1, 0(a5)
    j       1b

3:  /* печатаем то, что собрали */
    mv      a3, a5
1:  lbu     a4, 0(a3)
    beqz    a4, 2f
    jal     t6, putc
    addi    a3, a3, 1
    j       1b
2:  jr      t5


/* div10: делит a0 на десять.
   На выходе a0 частное, a1 остаток. Возврат через t3.

   Честное деление вычитанием: сколько раз десятка помещается в число,
   столько и частное, что осталось, то и остаток. Медленно и наглядно.
   Быстрые способы есть, но они начинаются с умножения, а его в RV32I
   тоже нет. */
div10:
    li      a1, 0               /* здесь копим частное */
    li      t1, 10
1:  blt     a0, t1, 2f          /* число меньше десяти: остаток готов */
    sub     a0, a0, t1
    addi    a1, a1, 1
    j       1b
2:  mv      t2, a0              /* остаток */
    mv      a0, a1              /* частное */
    mv      a1, t2
    jr      t3


    .section .rodata
msg_first:
    .string "2 + 2 = "
msg_second:
    .string "20000 + 2345 = "
msg_nl:
    .string "\n"

    .section .bss
    .align 2
numbuf:
    .space 16
