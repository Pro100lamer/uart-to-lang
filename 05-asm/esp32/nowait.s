// Опыт: что будет, если не ждать передатчик.
//
// Это тот же цикл, что в hello.s, но без ожидания. Ровно так написана
// первая программа серии, и в QEMU она работает безупречно: модель
// принимает байт мгновенно, сколько ни давай.
//
// Кристалл на 240 МГц кладёт байты в буфер быстрее, чем провод на
// 115200 их отдаёт. Лишние теряются, и из «Привет с железа!» выходит
// нечитаемая рвань. Печатаем по кругу, чтобы её было видно.

        .set    UART0_FIFO, 0x60000000

        .section .text
        .global _start
_start:
        movi    a3, message
        movi    a4, UART0_FIFO

next_char:
        l8ui    a5, a3, 0
        beqz    a5, done
        s32i    a5, a4, 0           // кладём и не смотрим, ушло ли
        addi    a3, a3, 1
        j       next_char

done:
        j       _start              // и снова сначала

        .section .rodata
message:
        .ascii  "Привет с железа!"
        .byte   13, 10, 0   // возврат каретки, перевод строки, ноль
