// Первая программа серии, тот же цикл, но на Xtensa и на живом ESP32.
//
// В первой статье этот цикл шёл в QEMU: взять байт, положить в UART,
// сдвинуться, повторить. Здесь он идёт на кристалле, и байты выходят
// в настоящий провод.
//
// Ради чего это в пятой статье: строка movi a3, message на кристалле
// НЕ ИСПОЛНЯЕТСЯ. Ассемблер меняет её на l32r, чтение слова данных,
// а само слово заполняет компоновщик.
//
// Две вещи, которых в эмуляторе не было, и обе стоили прогонов:
//
//   1. У регистров UART на ESP32 два адреса. Через 0x3FF40000 читаются
//      настройки, но буфер передачи доступен только через псевдоним
//      0x60000000.
//
//   2. Ждать передатчик обязательно. В QEMU байты уходят мгновенно, и
//      цикл без проверки работает. Кристалл на 240 МГц заполняет буфер
//      быстрее, чем провод на 115200 его отдаёт, и без ожидания из
//      «Привет с железа!» выходит рвань.

        .set    UART0_FIFO,   0x60000000  // буфер передачи, только этот адрес
        .set    UART0_STATUS, 0x3FF4001C  // состояние, биты 16..23 это очередь

        .section .text
        .global _start
_start:
        movi    a3, message         // адрес строки; станет l32r
        movi    a4, UART0_FIFO
        movi    a7, UART0_STATUS

next_char:
        l8ui    a5, a3, 0           // взять очередной байт
        beqz    a5, done            // ноль, строка кончилась

wait_tx:
        l32i    a6, a7, 0           // сколько байт ещё не ушло в провод
        extui   a6, a6, 16, 8
        bnez    a6, wait_tx         // пока не ноль, ждём

        s32i    a5, a4, 0           // положить байт в UART
        addi    a3, a3, 1           // сдвинуться на байт вперёд
        j       next_char

done:
        j       done                // дальше идти некуда

        .section .rodata
message:
        .ascii  "Привет с железа!"
        .byte   13, 10, 0   // возврат каретки, перевод строки, ноль
