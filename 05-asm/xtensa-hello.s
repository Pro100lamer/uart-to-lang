// Тот же скелет, что в первой программе серии, на Xtensa (ядро ESP32 LX6).
// Программа не запускается и не должна: сравниваем МНЕМОНИКИ.
// Запуск на живом кристалле лежит отдельно, в esp32-run/.
//
// Интересное место одно, и оно то же самое, что на ARM и на RISC-V:
//   movi a3, message  просит адрес строки, а адрес в команду не влезает.
//                     Ассемблер заводит слово данных в секции .literal
//                     и меняет movi на l32r, чтение этого слова. Само
//                     слово остаётся пустым: адрес впишет компоновщик.

        .text
        .global _start
_start:
        movi    a3, message         // адрес строки
        movi    a4, 1               // единица влезает в команду
next_char:
        l8ui    a5, a3, 0           // взять байт
        beqz    a5, done            // ноль, строка кончилась
        addi    a3, a3, 1           // сдвинуться вперёд
        j       next_char
done:
        nop
        ret

        .section .rodata
message:
        .asciz "Privet"
